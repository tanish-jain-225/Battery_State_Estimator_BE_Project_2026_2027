    endcase
end
always @(*) begin                    // stage S_MAC2
    sum66 = sub_r ? ($signed({{34{c_r[31]}}, c_r}) - rnd_r)
                  : ($signed({{34{c_r[31]}}, c_r}) + rnd_r);
    if (!sum66[65] && (|sum66[64:31]))      mac_res = I32_MAX;
    else if (sum66[65] && !(&sum66[64:31])) mac_res = I32_MIN;
    else                                    mac_res = sum66[31:0];
    if (clamp_r) begin
        if (mac_res < 0)          mac_res = 32'sd0;
        else if (mac_res > ONE30) mac_res = ONE30;
    end
end

// ---------------- OCV / slope ROMs with interpolation offset ----------------
reg  signed [31:0] lut_src_r;            // registered in S_FETCH
wire signed [31:0] lut_src = lut_src_r;
wire signed [31:0] lut_sh  = lut_src >>> 20;
wire [9:0] lut_addr = lut_src[31]            ? 10'd0 :
                      (lut_sh > 32'sd1023)   ? 10'd1023 : lut_sh[9:0];
wire signed [32:0] dl33 = {lut_src[31], lut_src} - $signed({3'b000, lut_addr, 20'd0});
wire signed [31:0] dl   = (dl33 > 33'sd2147483647)  ? I32_MAX :
                          (dl33 < -33'sd2147483648) ? I32_MIN : dl33[31:0];
reg signed [31:0] ocv_rom   [0:1023];
reg signed [31:0] slope_rom [0:1023];
reg signed [31:0] ocv_q, slope_q;
initial begin
    $readmemh(OCV_FILE, ocv_rom);
    $readmemh(SLOPE_FILE, slope_rom);
end
always @(posedge clk) begin
    ocv_q   <= ocv_rom[lut_addr];
    slope_q <= slope_rom[lut_addr];
end

// ---------------- sequential divider ----------------
reg  [61:0] div_num;
reg  [31:0] div_den;
reg  [32:0] div_rem;
reg  [61:0] div_quo;
reg  [5:0]  div_cnt;
reg         div_neg;
wire [32:0] rem_sh = {div_rem[31:0], div_num[61]};
wire        rem_ge = (rem_sh >= {1'b0, div_den});
wire [31:0] abs_ra = rf[u_ra][31] ? (~rf[u_ra] + 32'd1) : rf[u_ra];
wire [31:0] abs_rb = rf[u_rb][31] ? (~rf[u_rb] + 32'd1) : rf[u_rb];
reg  signed [31:0] div_res;
always @(*) begin
    if (!div_neg) div_res = (div_quo > 62'd2147483647) ? I32_MAX : $signed(div_quo[31:0]);
    else          div_res = (div_quo > 62'd2147483648) ? I32_MIN : $signed(~div_quo[31:0] + 32'd1);
end

// ---------------- sequential square root (restoring, 2 bits per cycle) ----------------
reg  [61:0] sq_rad;
reg  [35:0] sq_rem;
reg  [30:0] sq_root;
reg  [4:0]  sq_cnt;
wire [35:0] sq_rem_n = {sq_rem[33:0], sq_rad[61:60]};
wire [35:0] sq_trial = {3'b000, sq_root, 2'b01};
wire        sq_ge    = (sq_rem_n >= sq_trial);

// ---------------- control FSM ----------------
localparam S_IDLE = 4'd0, S_FETCH = 4'd1, S_MUL1 = 4'd2, S_MUL2 = 4'd3, S_RND = 4'd4,
           S_MAC2 = 4'd5, S_LUT2 = 4'd6, S_DIV = 4'd7, S_DIVW = 4'd8, S_SQ = 4'd9,
           S_SQW = 4'd10, S_DONE = 4'd11, S_LUT1 = 4'd12;
reg [3:0] state;
reg [5:0] rd_r;
assign busy = (state != S_IDLE);

task next_op;
begin
    if (pc == LAST_PC) state <= S_DONE;
    else begin pc <= pc + 7'd1; state <= S_FETCH; end
end
endtask

integer k;
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        state <= S_IDLE; pc <= 7'd0; done <= 1'b0; rd_r <= 6'd0;
        opa_r <= 32'sd0; opb_r <= 32'sd0; c_r <= 32'sd0; rnd_r <= 66'sd0;
        sc_r <= 2'd2; sub_r <= 1'b0; clamp_r <= 1'b0;
        div_num <= 62'd0; div_den <= 32'd1; div_rem <= 33'd0; div_quo <= 62'd0;
        div_cnt <= 6'd0; div_neg <= 1'b0;
        sq_rad <= 62'd0; sq_rem <= 36'd0; sq_root <= 31'd0; sq_cnt <= 5'd0; lut_src_r <= 32'sd0;
        for (k = 0; k < 64; k = k + 1) rf[k] <= 32'sd0;
    end else begin
        done <= 1'b0;
        if (cfg_we && state == S_IDLE) rf[cfg_addr] <= cfg_data;
        case (state)
        S_IDLE: if (start) begin pc <= 7'd0; state <= S_FETCH; end
        S_FETCH: begin
            rd_r <= u_rd;
            case (u_op)
            OP_MAC: begin
                opa_r <= rf[u_ra]; opb_r <= rf[u_rb]; c_r <= rf[u_rc];
                sc_r <= u_sc; sub_r <= u_sub; clamp_r <= u_clamp;
                state <= S_MUL1;
            end
            OP_LUT: begin lut_src_r <= rf[u_ra]; state <= S_LUT1; end
            OP_DIV: begin
                div_num <= u_f30 ? {abs_ra, 30'd0} : {2'b00, abs_ra, 28'd0};
                div_den <= abs_rb;
                div_neg <= rf[u_ra][31] ^ rf[u_rb][31];
                div_rem <= 33'd0; div_quo <= 62'd0; div_cnt <= 6'd62;
                state <= S_DIV;
            end
            default: begin                        // OP_SQRT
                sq_rad  <= rf[u_ra][31] ? 62'd0 : {1'b0, rf[u_ra][30:0], 30'd0};
                sq_rem  <= 36'd0; sq_root <= 31'd0; sq_cnt <= 5'd31;
                state   <= S_SQ;
            end
            endcase
        end
        S_MUL1: state <= S_MUL2;                  // mul_p1 <= opa_r*opb_r
        S_MUL2: state <= S_RND;                   // prod_r <= mul_p1
        S_RND:  begin rnd_r <= rounded; state <= S_MAC2; end
        S_MAC2: begin rf[rd_r] <= mac_res; next_op; end
        S_LUT1: state <= S_LUT2;                  // ROMs sample lut_addr on this edge
        S_LUT2: begin
            rf[rd_r] <= ocv_q; rf[R_SL] <= slope_q; rf[R_DL] <= dl;
            next_op;
        end
        S_DIV: begin
            div_rem <= rem_ge ? (rem_sh - {1'b0, div_den}) : rem_sh;
            div_quo <= {div_quo[60:0], rem_ge};
            div_num <= {div_num[60:0], 1'b0};
            div_cnt <= div_cnt - 6'd1;
            if (div_cnt == 6'd1) state <= S_DIVW;
        end
        S_DIVW: begin rf[rd_r] <= div_res; next_op; end
        S_SQ: begin
            sq_rem  <= sq_ge ? (sq_rem_n - sq_trial) : sq_rem_n;
            sq_root <= {sq_root[29:0], sq_ge};
            sq_rad  <= {sq_rad[59:0], 2'b00};
            sq_cnt  <= sq_cnt - 5'd1;
            if (sq_cnt == 5'd1) state <= S_SQW;
        end
        S_SQW: begin rf[rd_r] <= {1'b0, sq_root}; next_op; end
        S_DONE: begin done <= 1'b1; state <= S_IDLE; end
        default: state <= S_IDLE;
        endcase
        rf[R_ZERO] <= 32'sd0;                     // read-only constants
        rf[R_ONE]  <= ONE30;
    end
end

endmodule
