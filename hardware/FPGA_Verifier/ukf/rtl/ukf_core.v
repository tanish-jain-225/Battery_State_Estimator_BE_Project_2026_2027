// ukf_core.v -- fixed-point 1-RC Thevenin UKF for battery SOC (Rev 0.2)
//
// Rev 0.2: LUT source register (lut_src_r) added -- the register-file read no
//          longer feeds the ROM address clamp and the DL subtraction in the
//          same cycle. Same arithmetic (bit-exact); a LUT op takes 3 cycles.
//
// Same architecture as ekf_core Rev 0.3: one time-multiplexed, pipelined
// 32x32 MAC (FETCH -> MUL1 -> MUL2 -> RND -> MAC2), an FSM stepping through a
// fixed micro-program, OCV/slope ROMs, a sequential divider -- plus a
// sequential square-root unit for the 2x2 Cholesky factor.
//
// The micro-program (ukf_ucode.vh) is generated from the same op list that
// the golden model ukf_fixed.py executes (gen_ukf.py), so both run the
// identical operation sequence.
//
// Micro-ops:
//   MAC  rd = sat32(rc +/- ((ra*rb + 2^(s-1)) >>> s)), s in {26,28,30,32}, opt. clamp [0,1]
//   LUT  rd = OCV[k], SL = SLOPE[k], DL = sat32(ra - k*2^20), k = clamp(ra >>> 20, 0, 1023)
//   DIV  rd = sat32((ra << f) / rb), f in {28,30}, truncated toward zero
//   SQRT rd = floor(sqrt(max(ra,0) << 30))
//
// Interface: cfg_we/cfg_addr/cfg_data write any register while idle (constants,
// initial state, inputs I and Vmeas); start runs one predict+update step;
// done pulses when finished; soc_out = SOC estimate (Q2.30).
//////////////////////////////////////////////////////////////////////////////
