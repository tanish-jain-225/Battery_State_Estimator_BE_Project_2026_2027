#!/usr/bin/env python3
"""Generate everything ukf_core needs from the single PROGRAM in ukf_fixed.py.

usage: python3 gen_ukf.py [TEST_CELL] [OUT_DIR]        (default B0018, ./sim)
Writes:
  rtl/ukf_ucode.vh       micro-program (Verilog case items)  -- RTL include
  rtl/ukf_trace.vh       testbench trace header/line          -- TB include
  OUT/ukf_ocv.mem, OUT/ukf_slope.mem   ROM contents (fold-specific)
  OUT/ukf_stim.mem       stimulus
  OUT/golden_ukf_trace.csv
stim layout (32-bit hex words): n_cycles, steps;
  per cycle: n_writes, n_writes x (addr, data), steps x (I, Vmeas)
"""
import sys, os
from collections import OrderedDict
H = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [H, os.path.join(H, "../repo_fixed/hardware/FPGA_Verifier")]
from ukf_fixed import PROGRAM, R, REGS, TRACE, build_lut, build_consts, run_ukf_fixed, q, F28, F30

tc = sys.argv[1] if len(sys.argv) > 1 else "B0018"
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(H, "sim")
rtl = os.path.join(H, "rtl")
os.makedirs(out, exist_ok=True); os.makedirs(rtl, exist_ok=True)
h = lambda v: f"{v & 0xFFFFFFFF:08x}"

# ---------------- micro-program -> Verilog ----------------
SC = {26: 0, 28: 1, 30: 2, 32: 3}
OPC = {"MAC": 0, "LUT": 1, "DIV": 2, "SQRT": 3}
lines = [f"// Generated by gen_ukf.py from ukf_fixed.PROGRAM -- do not edit by hand.",
         f"// {len(PROGRAM)} micro-ops",
         f"localparam [6:0] LAST_PC = 7'd{len(PROGRAM) - 1};",
         f"localparam [5:0] R_SL = 6'd{R['SL']}, R_DL = 6'd{R['DL']}, R_X0 = 6'd{R['X0']}, R_ONE = 6'd{R['ONE']}, R_ZERO = 6'd{R['ZERO']};",
         "always @(*) begin",
         "    u_op = 2'd0; u_ra = R_ZERO; u_rb = R_ZERO; u_rc = R_ZERO; u_rd = R_ZERO;",
         "    u_sc = 2'd2; u_sub = 1'b0; u_clamp = 1'b0; u_f30 = 1'b0;",
         "    case (pc)"]
for pc, op in enumerate(PROGRAM):
    k = op[0]
    if k == "MAC":
        _, rd, ra, rb, rc, s, sub, cl = op
        body = (f"u_op=2'd0; u_ra=6'd{R[ra]}; u_rb=6'd{R[rb]}; u_rc=6'd{R[rc]}; u_rd=6'd{R[rd]}; "
                f"u_sc=2'd{SC[s]}; u_sub=1'b{sub}; u_clamp=1'b{cl};")
        cm = f"{rd} = {rc} {'-' if sub else '+'} rnd({ra}*{rb} >> {s}){' clamp' if cl else ''}"
    elif k == "LUT":
        _, rd, ra = op
        body = f"u_op=2'd1; u_ra=6'd{R[ra]}; u_rd=6'd{R[rd]};"
        cm = f"{rd}, SL, DL <- LUT({ra})"
    elif k == "DIV":
        _, rd, ra, rb, f = op
        body = f"u_op=2'd2; u_ra=6'd{R[ra]}; u_rb=6'd{R[rb]}; u_rd=6'd{R[rd]}; u_f30=1'b{1 if f == 30 else 0};"
        cm = f"{rd} = ({ra} << {f}) / {rb}"
    else:
        _, rd, ra = op
        body = f"u_op=2'd3; u_ra=6'd{R[ra]}; u_rd=6'd{R[rd]};"
        cm = f"{rd} = sqrt({ra})"
    lines.append(f"    7'd{pc}: begin {body} end  // {cm}")
lines += ["    default: ;", "    endcase", "end"]
open(os.path.join(rtl, "ukf_ucode.vh"), "w").write("\n".join(lines) + "\n")

cols = ["I", "VM"] + TRACE
tr = [f'// Generated by gen_ukf.py -- testbench trace format',
      f'`define UKF_TRACE_HDR "step,t,{",".join(c.lower() for c in cols)}\\n"',
      f'`define UKF_R_I {R["I"]}', f'`define UKF_R_VM {R["VM"]}',
      '`define UKF_TRACE_LINE(fd, n, t) $fwrite(fd, "%0d,%0d' + ",%08h" * len(cols) + '\\n", n, t'
      + "".join(f", dut.rf[{R[c]}]" for c in cols) + ")"]
open(os.path.join(rtl, "ukf_trace.vh"), "w").write("\n".join(tr) + "\n")

# ---------------- fold vectors + golden trace ----------------
from real_nasa_dataset import generate_nasa_battery_dataset
from real_ekf_baseline import fit_ekf_baseline
rows, meta = generate_nasa_battery_dataset()
cyc = OrderedDict()
for r in rows:
    cyc.setdefault((r["battery"], r["cycle"]), []).append(r)
p = fit_ekf_baseline([r for r in rows if r["battery"] != tc])
lut = build_lut(p["ocv_poly"])
cap = meta[tc]["cap_nominal"]
keys = [k for k in cyc if k[0] == tc]
open(os.path.join(out, "ukf_ocv.mem"), "w").write("\n".join(h(v) for v in lut[0]) + "\n")
open(os.path.join(out, "ukf_slope.mem"), "w").write("\n".join(h(v) for v in lut[1]) + "\n")

stim, trace = [len(keys), len(cyc[keys[0]])], []
for k in keys:
    rr = cyc[k]
    c = build_consts(p, cap, rr[0]["dt"])
    w = dict(c)
    w.update(X0=q(rr[0]["soc_true"], F30), V1=0, P00=c["P0"], P01=0, P11=c["P0"])
    stim.append(len(w))
    for name, val in w.items():
        stim += [R[name], val]
    for r in rr:
        stim += [q(r["current_measured"], F28), q(r["voltage_measured"], F28)]
    run_ukf_fixed(rr, c, lut, trace)
open(os.path.join(out, "ukf_stim.mem"), "w").write("\n".join(h(v) for v in stim) + "\n")
with open(os.path.join(out, "golden_ukf_trace.csv"), "w") as f:
    f.write("step,t," + ",".join(c.lower() for c in cols) + "\n")
    for n, d in enumerate(trace):
        f.write(f"{n},{d['t']}," + ",".join(h(d[c]) for c in cols) + "\n")
print(f"{tc}: {len(keys)} cycles, {len(trace)} steps, {len(PROGRAM)} micro-ops -> {out}")
